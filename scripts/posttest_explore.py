"""EXPLORATORY POST-TEST checks (docs/lab-notebook.md, 2026-10-14, section "Exploratory post-test").

Not part of the pre-registered analysis. Uses only the per-sample CSVs already computed by evaluate.py
(eval_val_samples.csv, eval_test_samples.csv) and the run configs; the test inputs / targets are read on the CPU for
sample properties and for the figure (CPU inference of 4 MD8 runs on 3 samples, Mamba reference path). No training.

  1  per-seed table (night, commit) of rel_all, rel_p, rel_vy on validation and test; seeds 3-7 minus 0-2 per
     configuration with the Welch SE
  2  between-seed variance of rel_all, variant vs B: F ratio (two-sided p, df (k-1, k_B-1)) and a seed bootstrap CI of
     the SD ratio; per-sample / per-profile contributions to the between-seed variance of mean rel_all on test
     (covariance decomposition: Var(mean_i r_is) = sum_i (1/N^2) sum_j cov(r_i, r_j), the i-th term is sample i's share)
  3  figure: the 3 test samples with the largest contribution for MD8, target and predictions of 2 "good" and 2 "bad"
     MD8 seeds (p and vx)

Usage: python scripts/posttest_explore.py [--out-dir docs/results/posttest] [--fig-dir docs/figures/posttest]
"""

import argparse
import csv
import json
import math
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))

os.environ.setdefault("MPLBACKEND", "Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch

import analyze_val as av
from mdf import explore, models, runinfo

R = Path.home() / "runs"
CONFIGS = {
    "B": [R / "night1" / f"ep133_s{s}" for s in range(3)] + [R / "night3" / f"B_s{s}" for s in range(3, 8)],
    **{c: [R / "night2" / f"{c}_s{s}" for s in range(3)] + [R / "night3" / f"{c}_s{s}" for s in range(3, 8)]
       for c in ("MD8", "SA8", "MD32", "SA32", "B-large")},
    "CBAM8": [R / "night2" / f"CBAM8_s{s}" for s in range(3)],
}
METRICS = ("rel_all", "rel_p", "rel_vy")
SPLITS = ("val", "test")


def _betacf(a, b, x, itmax=300, eps=3e-16):
    """Continued fraction of the regularized incomplete beta (Numerical Recipes, betacf)."""
    qab, qap, qam = a + b, a + 1.0, a - 1.0
    c, d = 1.0, 1.0 - qab * x / qap
    d = 1.0 / (d if abs(d) > 1e-300 else 1e-300)
    h = d
    for m in range(1, itmax + 1):
        m2 = 2 * m
        aa = m * (b - m) * x / ((qam + m2) * (a + m2))
        d = 1.0 + aa * d
        d = 1.0 / (d if abs(d) > 1e-300 else 1e-300)
        c = 1.0 + aa / c if abs(1.0 + aa / c) > 1e-300 else 1e-300
        h *= d * c
        aa = -(a + m) * (qab + m) * x / ((a + m2) * (qap + m2))
        d = 1.0 + aa * d
        d = 1.0 / (d if abs(d) > 1e-300 else 1e-300)
        c = 1.0 + aa / c if abs(1.0 + aa / c) > 1e-300 else 1e-300
        de = d * c
        h *= de
        if abs(de - 1.0) < eps:
            break
    return h


def betainc(a, b, x):
    """Regularized incomplete beta I_x(a, b)."""
    if x <= 0:
        return 0.0
    if x >= 1:
        return 1.0
    lbt = math.lgamma(a + b) - math.lgamma(a) - math.lgamma(b) + a * math.log(x) + b * math.log(1 - x)
    if x < (a + 1) / (a + b + 2):
        return math.exp(lbt) * _betacf(a, b, x) / a
    return 1.0 - math.exp(lbt) * _betacf(b, a, 1 - x) / b


def f_cdf(f, d1, d2):
    return betainc(d1 / 2, d2 / 2, d1 * f / (d1 * f + d2))


def per_sample(run, split):
    with open(run / f"eval_{split}_samples.csv") as fh:
        rows = list(csv.DictReader(fh))
    return [r["file"] for r in rows], {m: np.array([float(r[m]) for r in rows]) for m in METRICS}


def welch(a, b):
    a, b = np.asarray(a), np.asarray(b)
    se = np.sqrt(a.var(ddof=1) / a.size + b.var(ddof=1) / b.size)
    return b.mean() - a.mean(), se


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out-dir", type=Path, default=Path("docs/results/posttest"))
    ap.add_argument("--fig-dir", type=Path, default=Path("docs/figures/posttest"))
    ap.add_argument("--n-boot", type=int, default=10000)
    args = ap.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    args.fig_dir.mkdir(parents=True, exist_ok=True)
    md = ["# Exploratory post-test checks (NOT pre-registered)", "",
          f"Generated by `scripts/posttest_explore.py`, git {runinfo.git_info()}, {runinfo.utc_now()}.", ""]

    # --- per-run values ---
    data, files, table = {}, {}, []
    for label, runs in CONFIGS.items():
        for run in runs:
            cfg = json.loads((run / "config.json").read_text())
            row = {"config": label, "seed": cfg["seed"], "night": run.parent.name, "commit": cfg["git"]["commit"][:7]}
            for split in SPLITS:
                f, d = per_sample(run, split)
                files.setdefault(split, f)
                assert files[split] == f
                data[(label, cfg["seed"], split)] = d
                for m in METRICS:
                    row[f"{split}_{m}"] = 100 * d[m].mean()
            table.append(row)
    av.write_csv(args.out_dir / "per_seed.csv", table)
    md += ["## 1a Per-seed values (%)", "", av.md_table(table, list(table[0].keys()),
           {k: (lambda v: f"{v:.3f}") for k in table[0] if "_rel_" in k}), ""]

    # MD8 groups on test (by rel_all)
    md8 = sorted([(r["test_rel_all"], r["seed"], r["night"]) for r in table if r["config"] == "MD8"])
    md += ["MD8 on test, sorted by rel_all: " + ", ".join(f"s{s} ({n}) {v:.3f}" for v, s, n in md8), ""]

    # --- 1b seeds 3-7 minus 0-2 ---
    t1b = []
    for label in CONFIGS:
        rr = [r for r in table if r["config"] == label]
        if len(rr) < 8:
            continue
        row = {"config": label}
        for split in SPLITS:
            for m in METRICS:
                a = [r[f"{split}_{m}"] for r in rr if r["seed"] <= 2]
                b = [r[f"{split}_{m}"] for r in rr if r["seed"] >= 3]
                d, se = welch(a, b)
                row[f"{split} {m}"] = f"{d:+.3f} ({d / se:+.2f})"
                row[f"_{split}_{m}_z"] = d / se
        t1b.append(row)
    av.write_csv(args.out_dir / "seeds37_minus_02.csv", t1b)
    shown = [k for k in t1b[0] if not k.startswith("_")]
    zs = {f"{s}_{m}": [r[f"_{s}_{m}_z"] for r in t1b] for s in SPLITS for m in METRICS}
    md += ["## 1b Seeds 3-7 minus seeds 0-2 (points; diff / Welch SE in brackets)", "",
           av.md_table(t1b, shown), "",
           "Summary over the 6 configurations (mean of diff/SE; number positive): " + "; ".join(
               f"{k} {np.mean(v):+.2f} ({sum(x > 0 for x in v)}/6)" for k, v in zs.items()), ""]

    # --- 2a variance ratios ---
    rng = np.random.default_rng(0)
    t2 = []
    for split in SPLITS:
        b = np.array([r[f"{split}_rel_all"] for r in table if r["config"] == "B"])
        for label in CONFIGS:
            if label == "B":
                continue
            v = np.array([r[f"{split}_rel_all"] for r in table if r["config"] == label])
            f = v.var(ddof=1) / b.var(ddof=1)
            dfn, dfd = v.size - 1, b.size - 1
            cdf = f_cdf(f, dfn, dfd)
            p = 2 * min(cdf, 1 - cdf)
            bv = v[rng.integers(0, v.size, (args.n_boot, v.size))].std(axis=1, ddof=1)
            bb = b[rng.integers(0, b.size, (args.n_boot, b.size))].std(axis=1, ddof=1)
            ok = bb > 0
            ratio = bv[ok] / bb[ok]
            t2.append({"split": split, "config": label, "seeds": f"{v.size}/{b.size}", "sd_var": v.std(ddof=1),
                       "sd_B": b.std(ddof=1), "sd_ratio": np.sqrt(f), "F": f, "p_F_two_sided": p,
                       "sd_ratio_CI_lo": np.percentile(ratio, 2.5), "sd_ratio_CI_hi": np.percentile(ratio, 97.5)})
    av.write_csv(args.out_dir / "variance_ratio.csv", t2)
    md += ["## 2a Between-seed spread of rel_all, variant vs B", "",
           "F = var_variant / var_B (sample variances over seeds), two-sided p of the F distribution (assumes normal "
           "per-run values); CI: bootstrap over seeds (10 000) of the SD ratio, percentile.", "",
           av.md_table(t2, list(t2[0].keys()), {k: (lambda v: f"{v:.3g}") for k in t2[0] if k not in
                                                ("split", "config", "seeds")}), ""]

    # --- 2b per-sample contributions on test ---
    ds = explore.load_split("test", allow_test=True)
    assert ds.files == files["test"]
    props = explore.sample_properties(ds)
    n = len(ds)
    tgt = ds.targets.numpy()
    rev = []
    for i in range(n):
        mask = ds.inputs[i, 2].numpy() > 0.5
        te_r, _ = explore.trailing_edge(mask)
        down = (~mask) & (np.arange(128)[:, None] > te_r)
        rev.append(int((tgt[i, 1][down] < 0).sum()))
    contrib_rows, prof_rows = [], []
    for label in ("MD8", "SA8", "B"):
        m = np.stack([data[(label, s, "test")]["rel_all"] for s in range(8)])  # (8, N)
        cov = np.cov(m.T)  # (N, N), ddof 1
        share = cov.sum(axis=1) / n ** 2
        total = m.mean(axis=1).var(ddof=1)
        assert np.isclose(share.sum(), total)
        for i in range(n):
            contrib_rows.append({"config": label, "file": ds.files[i], "profile": props[i]["profile"],
                                 "abs_alpha": props[i]["abs_alpha_deg"], "sum_abs_p": props[i]["sum_abs_p_tgt"],
                                 "reverse_flow_cells": rev[i], "mean_rel_all": m[:, i].mean(),
                                 "sd_seeds_rel_all": m[:, i].std(ddof=1), "share_of_var": share[i] / total})
        by_prof = {}
        for i in range(n):
            by_prof.setdefault(props[i]["profile"], []).append(i)
        for p_, idx in by_prof.items():
            prof_rows.append({"config": label, "profile": p_, "share_of_var": share[idx].sum() / total,
                              "mean_abs_alpha": np.mean([props[i]["abs_alpha_deg"] for i in idx])})
    av.write_csv(args.out_dir / "test_variance_contrib_samples.csv", contrib_rows)
    av.write_csv(args.out_dir / "test_variance_contrib_profiles.csv", prof_rows)
    md += ["## 2b Which test samples / profiles make the between-seed variance of mean rel_all", "",
           "share_of_var = sample's term of the covariance decomposition / total variance (shares sum to 1; a "
           "term can be negative). reverse_flow_cells = target fluid cells with vx < 0 downstream of the trailing "
           "edge (separated flow).", ""]
    for label in ("MD8", "SA8", "B"):
        cr = sorted([r for r in contrib_rows if r["config"] == label], key=lambda r: -r["share_of_var"])
        pr = sorted([r for r in prof_rows if r["config"] == label], key=lambda r: -r["share_of_var"])
        top3p = sum(r["share_of_var"] for r in pr[:3])
        top5s = sum(r["share_of_var"] for r in cr[:5])
        md += [f"### {label}: top 5 samples ({100 * top5s:.0f} % of the variance); top 3 profiles "
               f"{', '.join(r['profile'] for r in pr[:3])} ({100 * top3p:.0f} %)", "",
               av.md_table(cr[:8], ["file", "abs_alpha", "sum_abs_p", "reverse_flow_cells", "mean_rel_all",
                                    "sd_seeds_rel_all", "share_of_var"],
                           {"abs_alpha": lambda v: f"{v:.1f}", "sum_abs_p": lambda v: f"{v:.0f}",
                            "mean_rel_all": lambda v: f"{100 * v:.2f}", "sd_seeds_rel_all": lambda v: f"{100 * v:.2f}",
                            "share_of_var": lambda v: f"{100 * v:.1f} %"}), ""]
    alpha = np.array([p["abs_alpha_deg"] for p in props])
    md += [f"Test set: |alpha| median {np.median(alpha):.1f} deg (max {alpha.max():.1f}); samples with reverse flow "
           f"cells > 100: {sum(r > 100 for r in rev)} of {n}.", ""]

    # --- 2c sensitivity (post hoc): without the profile with the largest share for MD8 ---
    top_prof = sorted([r for r in prof_rows if r["config"] == "MD8"], key=lambda r: -r["share_of_var"])[0]["profile"]
    keep = np.array([p["profile"] != top_prof for p in props])
    t2c = []
    b_wo = np.array([data[("B", s, "test")]["rel_all"][keep].mean() for s in range(8)])
    for label, runs in CONFIGS.items():
        seeds = range(len(runs))
        full = np.array([data[(label, s, "test")]["rel_all"].mean() for s in seeds])
        wo = np.array([data[(label, s, "test")]["rel_all"][keep].mean() for s in seeds])
        f = wo.var(ddof=1) / b_wo.var(ddof=1)
        cdf = f_cdf(f, wo.size - 1, b_wo.size - 1)
        t2c.append({"config": label, "seeds": wo.size, "rel_all_all": f"{100 * full.mean():.3f} ({100 * full.std(ddof=1):.3f})",
                    f"rel_all_without_{top_prof}": f"{100 * wo.mean():.3f} ({100 * wo.std(ddof=1):.3f})",
                    "sd_ratio_vs_B_without": f"{np.sqrt(f):.2f}" if label != "B" else "",
                    "p_F_without": f"{2 * min(cdf, 1 - cdf):.3f}" if label != "B" else ""})
    av.write_csv(args.out_dir / "sensitivity_without_top_profile.csv", t2c)
    md += [f"## 2c Sensitivity (post hoc): test rel_all without profile `{top_prof}` ({int((~keep).sum())} of {n} "
           "samples), mean (sd over seeds), %", "", av.md_table(t2c, list(t2c[0].keys())), ""]

    # --- 3 figure ---
    cr = sorted([r for r in contrib_rows if r["config"] == "MD8"], key=lambda r: -r["share_of_var"])[:3]
    order = [s for _, s, _ in md8]  # by test rel_all, ascending
    good, bad = order[:2], order[-2:]
    show = [("good", s) for s in good] + [("bad", s) for s in bad]
    nets = {}
    for _, s in show:
        run = CONFIGS["MD8"][s]
        mcfg = models.model_cfg_from_run_config(json.loads((run / "config.json").read_text()))
        mcfg["mamba_impl"] = "ref"  # CPU, reference scan, same parameters
        net = models.build_from_cfg(mcfg)
        net.load_state_dict(torch.load(run / "model.pt", map_location="cpu", weights_only=True))
        nets[s] = net.eval()
    fig, axes = plt.subplots(6, 5, figsize=(12, 15), constrained_layout=True)
    for k, r in enumerate(cr):
        i = ds.files.index(r["file"])
        mask = ds.inputs[i, 2].numpy() > 0.5
        with torch.no_grad():
            preds = {s: nets[s](ds.inputs[i:i + 1])[0].numpy() for _, s in show}
        for j, (ch, cname) in enumerate(((0, "p"), (1, "vx"))):
            ax_row = axes[2 * k + j]
            lim = np.abs(tgt[i, ch]).max()
            panels = [("target", tgt[i, ch])] + [
                (f"MD8 s{s} ({g}) rel_all {100 * data[('MD8', s, 'test')]['rel_all'][i]:.2f}", preds[s][ch])
                for g, s in show]
            for ax, (title, img) in zip(ax_row, panels):
                ax.imshow(np.where(mask, np.nan, img), cmap="RdBu_r", vmin=-lim, vmax=lim)
                ax.set_title(f"{cname} {title}", fontsize=7)
                ax.set_xticks([]), ax.set_yticks([])
        axes[2 * k, 0].set_ylabel(f"{r['file']}\n|alpha| {r['abs_alpha']:.1f}, share {100 * r['share_of_var']:.0f} %",
                                  fontsize=7)
    fig.suptitle("EXPLORATORY POST-TEST: test samples with the largest share of MD8's between-seed variance; "
                 f"good seeds {good}, bad seeds {bad} (by test rel_all); flow downwards", fontsize=9)
    fig.savefig(args.fig_dir / "md8_top3_samples.png", dpi=100)
    plt.close(fig)
    md += [f"Figure `md8_top3_samples.png`: samples {', '.join(r['file'] for r in cr)}; good seeds {good}, bad "
           f"seeds {bad}.", ""]
    (args.out_dir / "summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
